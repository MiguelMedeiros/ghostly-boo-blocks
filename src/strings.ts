/** Each language by its primary subtag, with the tag the page's `<html lang>` gets. */
const LANGUAGES: Record<string, { lang: string; strings: Strings }> = {
  en: { lang: "en", strings: en },
  pt: { lang: "pt-BR", strings: pt },
  es: { lang: "es", strings: es },
  fr: { lang: "fr", strings: fr },
  it: { lang: "it", strings: it },
  ja: { lang: "ja", strings: ja },
  zh: { lang: "zh-CN", strings: zh },
  ar: { lang: "ar", strings: ar },
};

/** The page's language and direction for a BCP 47 tag, by its primary subtag (`es-MX` reads Spanish); English otherwise. */
export function stringsFor(locale: string | undefined): { lang: string; dir: "ltr" | "rtl"; strings: Strings } {
  const picked = LANGUAGES[(locale ?? "").toLowerCase().split(/[-_]/)[0]!] ?? LANGUAGES.en!;
  return { ...picked, dir: picked.strings === ar ? "rtl" : "ltr" };
}
